function getStringsForLang(code) {
  if (translations[code]) {
    return translations[code];
  }
  return { ...translations.en };
}

function buildXml(dict) {
  let xml = '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n';
  for (const [key, val] of Object.entries(dict)) {
    const escaped = val
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/'/g, "\\'")
      .replace(/"/g, '\\"');
    xml += `    <string name="${key}">${escaped}</string>\n`;
  }
  xml += '</resources>\n';
  return xml;
}

// Ensure default strings.xml has all keys
const defaultXml = buildXml(translations.en);
fs.writeFileSync(path.join(targetResDir, 'values', 'strings.xml'), defaultXml, 'utf8');
console.log('Updated default res/values/strings.xml');

let count = 0;
for (const code of all50Codes) {
  const dirName = code === 'en' ? 'values' : `values-${code}`;
  const dirPath = path.join(targetResDir, dirName);
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
  const dict = getStringsForLang(code);
  const xml = buildXml(dict);
  fs.writeFileSync(path.join(dirPath, 'strings.xml'), xml, 'utf8');
  count++;
}

console.log(`Successfully generated localized strings.xml for all ${count} languages!`);
